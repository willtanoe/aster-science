#!/usr/bin/env node
// Write env.local.cmd from ASTER_ENV_* variables.
//
// Values travel through environment variables so cmd never has to re-parse
// embedded JSON quotes. `%` is doubled so a literal percent survives batch
// expansion, and every value is wrapped in set "...", which keeps quotes,
// ampersands and parentheses literal at load time.
//
// Usage (from install.cmd): set ASTER_ENV_* then node tools/write-env.mjs

import fs from 'node:fs';

const e = process.env;
const esc = (v) => String(v ?? '').replace(/%/g, '%%');

let map = e.ASTER_ENV_MAP || '';
if (map.startsWith('@')) {
  const file = map.slice(1);
  try {
    map = fs.readFileSync(file, 'utf8').trim();
  } catch (err) {
    console.error(`[env] cannot read model map file ${file}: ${err.message}`);
    process.exit(1);
  }
}
if (map) {
  try {
    const parsed = JSON.parse(map);
    if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
      throw new Error('expected a JSON object mapping alias to model or route');
    }
  } catch (err) {
    console.error(`[env] ASTER_MODEL_MAP is invalid: ${err.message}`);
    process.exit(1);
  }
}

const lines = [
  '@echo off',
  'rem Generated by tools/write-env.mjs — gitignored, never commit credentials.',
];

const add = (name, value) => {
  if (value === undefined || value === '') return;
  lines.push(`set "${name}=${esc(value)}"`);
};

add('ASTER_OPENAI_BASE_URL', e.ASTER_ENV_BASE);
add('ASTER_OPENAI_API_KEY', e.ASTER_ENV_KEY);
add('ASTER_OPENAI_MODEL', e.ASTER_ENV_MODEL);
add('ASTER_MODEL_MAP', map);

fs.writeFileSync('env.local.cmd', lines.join('\r\n') + '\r\n');
console.log('[env] wrote env.local.cmd');
