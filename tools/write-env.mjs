#!/usr/bin/env node
// Write env.local.sh (sourced by the launcher and the proxy) from
// ASTER_ENV_BASE / ASTER_ENV_KEY / ASTER_ENV_MODEL / ASTER_ENV_MAP, or from
// positional arguments.
//
// The map argument is inline JSON or @path/to/map.json. It is validated here
// with the same rules the proxy applies at startup, so a typo fails the
// install instead of surfacing as a broken model picker later.
//
// Usage:
//   node tools/write-env.mjs [base_url] [api_key] [model] [map|@map.json]

import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const base = (args[0] ?? process.env.ASTER_ENV_BASE ?? '').trim();
const key = (args[1] ?? process.env.ASTER_ENV_KEY ?? '').trim();
const model = (args[2] ?? process.env.ASTER_ENV_MODEL ?? '').trim() || 'gpt-4o';
let map = (args[3] ?? process.env.ASTER_ENV_MAP ?? '').trim();

if (!base) {
  console.error('[env] a base URL is required (e.g. https://api.openai.com/v1)');
  process.exit(1);
}
try {
  new URL(base);
} catch {
  console.error(`[env] base URL is not a valid URL: ${base}`);
  process.exit(1);
}
if (!key) {
  console.error('[env] an API key is required');
  process.exit(1);
}

if (map.startsWith('@')) {
  const file = map.slice(1);
  try {
    map = fs.readFileSync(file, 'utf8').trim();
  } catch (e) {
    console.error(`[env] cannot read ${file}: ${e.message}`);
    process.exit(1);
  }
}

if (map) {
  let parsed;
  try {
    parsed = JSON.parse(map);
  } catch (e) {
    console.error(`[env] model map is not valid JSON: ${e.message}`);
    process.exit(1);
  }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    console.error('[env] model map must be a JSON object of alias -> model');
    process.exit(1);
  }
  for (const [alias, value] of Object.entries(parsed)) {
    if (!alias.trim()) {
      console.error('[env] model map has an empty alias');
      process.exit(1);
    }
    if (typeof value === 'string' && value.trim()) continue;
    if (value && typeof value === 'object' && typeof value.model === 'string' && value.model.trim()) {
      if (value.base_url !== undefined) {
        try {
          new URL(String(value.base_url));
        } catch {
          console.error(`[env] model map "${alias}".base_url is not a valid URL`);
          process.exit(1);
        }
      }
      continue;
    }
    console.error(`[env] model map "${alias}" must be a model id or {model, base_url?, api_key?}`);
    process.exit(1);
  }
  map = JSON.stringify(parsed);
}

// Single-quoted shell strings: embed a literal quote as '\''.
const quote = (s) => `'${s.replace(/'/g, `'\\''`)}'`;

const lines = [
  '# Generated by tools/write-env.mjs — never committed.',
  `export ASTER_OPENAI_BASE_URL=${quote(base)}`,
  `export ASTER_OPENAI_API_KEY=${quote(key)}`,
  `export ASTER_OPENAI_MODEL=${quote(model)}`,
  ...(map ? [`export ASTER_MODEL_MAP=${quote(map)}`] : []),
  '',
];

const out = path.join(process.cwd(), 'env.local.sh');
fs.writeFileSync(out, lines.join('\n'), { mode: 0o600 });
console.log(`[env] wrote ${out}`);
