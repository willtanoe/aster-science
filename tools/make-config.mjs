#!/usr/bin/env node
// Generate config.toml with absolute paths for this checkout.
//
// Relative paths are accepted by the app but are resolved against the current
// working directory at each use (kernels and MCP servers run in workspaces),
// so the instance config pins absolute paths that are valid everywhere.
//
// On macOS the daemon refuses a data dir outside $HOME or one that overlaps a
// writable sandbox root (for example /tmp). This tool checks that up front.
//
// Usage: node tools/make-config.mjs [--force]

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const force = process.argv.includes('--force');
const root = process.cwd();
const out = path.join(root, 'config.toml');

if (fs.existsSync(out) && !force) {
  console.log('[config] config.toml already exists (use --force to rewrite)');
  process.exit(0);
}

const data = path.join(root, 'claude-science-data').replace(/\\/g, '/');

if (process.platform === 'darwin') {
  const home = fs.realpathSync(os.homedir());
  const real = fs.existsSync(data) ? fs.realpathSync(data) : path.join(home, path.relative(home, data));
  if (!real.startsWith(home + path.sep)) {
    console.error(`[config] ${data} is outside ${home}.`);
    console.error('[config] The macOS daemon refuses a data dir outside your home directory.');
    console.error('[config] Move this folder under your home directory and re-run.');
    process.exit(1);
  }
  const tmp = fs.realpathSync(os.tmpdir());
  if (real === tmp || real.startsWith(tmp + path.sep)) {
    console.error(`[config] ${data} is inside ${tmp}.`);
    console.error('[config] The macOS daemon refuses a data dir inside the system temp folder.');
    process.exit(1);
  }
}

const toml = [
  '# Generated by tools/make-config.mjs — absolute paths for this machine.',
  '# data_dir/auth_dir/conda_home/venvs_base keep every download and every',
  '# piece of state inside this folder instead of ~/.claude-science.',
  '',
  `data_dir = '${data}'`,
  '',
  '[paths]',
  `auth_dir = '${data}/auth'`,
  `conda_home = '${data}/conda'`,
  `venvs_base = '${data}/venvs'`,
  '',
].join('\n');

fs.writeFileSync(out, toml);
console.log(`[config] wrote ${out}`);
